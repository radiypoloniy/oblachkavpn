# Клиент обращается к пользователю на «вы». Проверка ловит возврат к «ты»
# в строках интерфейса и сообщениях об ошибках.
#
# Это грубая проверка по списку форм, а не разбор языка: она ловит типовые случаи
# («Проверь», «Добавь», «твой»), но не заменяет вычитку новых текстов.
$ErrorActionPreference = 'Stop'

$informal = @(
    # Повелительное наклонение единственного числа
    'останови', 'запусти', 'подключи', 'восстанови', 'попробуй', 'проверь', 'добавь', 'выбери',
    'вставь', 'используй', 'открой', 'скопируй', 'нажми', 'укажи', 'переименуй',
    'сверь', 'отключи', 'включи', 'убедись', 'подожди', 'смени', 'сделай', 'удали',
    'закрой', 'повтори', 'обнови', 'перезапусти', 'сохрани', 'напиши', 'освободи',
    # Прошедшее время второго лица единственного числа
    'скопировал', 'ввёл', 'вставил', 'выбрал', 'указал', 'запустил',
    # Притяжательные
    'твой', 'твоя', 'твоё', 'твои', 'твою', 'твоего', 'тебе', 'тебя'
)
# Границы слова: иначе «включи» совпадёт внутри «включите», а «удали» внутри «удалить».
$pattern = '(?<![а-яёa-z])(' + ($informal -join '|') + ')(?![а-яё])'

$roots = @((Join-Path $PSScriptRoot 'src'), (Join-Path $PSScriptRoot 'tests')) | Where-Object { Test-Path -LiteralPath $_ }
$violations = @()
foreach ($file in Get-ChildItem -LiteralPath $roots -File -Recurse | Where-Object {
    $_.Extension -in @('.cs', '.xaml') -and $_.FullName -notmatch '\\(obj|bin)\\'
}) {
    $number = 0
    foreach ($line in [IO.File]::ReadAllLines($file.FullName, [Text.UTF8Encoding]::new($false))) {
        $number++
        $match = [regex]::Match($line, $pattern, 'IgnoreCase')
        if ($match.Success) { $violations += ($file.Name + ':' + $number + ' — «' + $match.Value + '»') }
    }
}
if ($violations.Count -gt 0) {
    throw ('Клиент обращается на «вы». Исправьте: ' + ($violations -join '; '))
}
Write-Host 'Тексты интерфейса: обращение на «вы» выдержано.'
